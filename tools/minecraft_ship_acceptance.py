"""Exercise the optional v0.1 ship route on the isolated fixture."""
import argparse
import re
import time

from minecraft_acceptance import Acceptance, NAMES


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--sandbox', required=True)
    args = parser.parse_args()
    test = Acceptance(args.sandbox)
    try:
        test.cmd('tick freeze')
        test.prepare()
        test.cmd('tp @a 0 251 40')
        test.cmd('execute as IE_TestD run function escape_island:player/reset')
        test.cmd('tag IE_TestD add role.engineer')
        test.cmd('tp IE_TestD -30.0 251.0 16.0')
        test.cmd('scoreboard players operation $game ship_parts = Tunable tunable.ship_parts_required')
        test.cmd('scoreboard players set $game ship_bonus_tick 9')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('inactive engineer cannot repair unattended ship', test.score('$ship_count', 'ship_progress') == 0 and test.score('$ship_delta', 'ship_progress') == 0)
        test.cmd('summon minecraft:marker -30 251 16 {Tags:["entity.engineer_battery","skill.battery.active"]}')
        test.cmd('scoreboard players set $game ship_bonus_tick 5')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('battery cannot repair unattended ship', test.score('$ship_delta', 'ship_progress') == 0)
        test.cmd('kill @e[type=minecraft:marker,tag=entity.engineer_battery]')
        test.cmd('execute as IE_TestA run function escape_island:role/_tag_captain')
        test.cmd('tp IE_TestA -30.0 251.0 16.0')
        test.cmd('scoreboard players set $game ship_bonus_tick 9')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('inactive engineer does not boost another repairer', test.score('$ship_delta', 'ship_progress') == 1)
        test.cmd('execute as IE_TestA run function escape_island:role/_tag_engineer')
        test.cmd('scoreboard players set $game ship_bonus_tick 9')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('active engineer boosts ship repair', test.score('$ship_delta', 'ship_progress') == 2)
        test.cmd('execute as IE_TestA run function escape_island:role/_tag_mechanic')
        test.cmd('scoreboard players set $game ship_bonus_tick 2')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('active mechanic boosts ship repair', test.score('$ship_delta', 'ship_progress') == 2)
        test.cmd('execute as IE_TestA run function escape_island:role/_tag_captain')
        test.cmd('tag IE_TestD remove role.engineer')
        test.cmd('tag IE_TestD add infected.common')
        test.cmd('scoreboard players set $game ship_bonus_tick 9')
        test.cmd('function escape_island:task/ship_dock_tick')
        test.check('inactive infected cannot suppress ship repair', test.score('$ship_delta', 'ship_progress') == 1)
        test.prepare()
        test.cmd('function escape_island:game/phase_2_awakening')
        test.cmd('scoreboard players set $game phase_timer 3599')
        test.sprint(2)
        test.check('ship route reaches repair phase', test.score('$game', 'cur_phase') == 3)
        mother = next(name for name in NAMES if test.count(f'@a[name={name},tag=infected.mother]'))
        human = next(name for name in NAMES if name != mother)
        test.cmd('tp @a 0 251 40')
        test.cmd(f'tp {human} -30.0 251.0 16.0')
        for number, (item, part) in enumerate((('iron_ingot', 'propeller'), ('copper_ingot', 'fuel_pump'), ('stick', 'steering_linkage')), 1):
            test.cmd(f'item replace entity {human} hotbar.0 with minecraft:{item}[custom_data={{item:"ship_part",part:"{part}"}},consumable={{animation:"spyglass",consume_seconds:999,has_consume_particles:false,sound:{{sound_id:""}}}}]')
            test.client_request('/action', {'name': human, 'action': 'slot', 'slot': 0})
            test.sprint(2)
            time.sleep(.3)
            test.client_request('/action', {'name': human, 'action': 'use'})
            time.sleep(.3)
            test.sprint(25)
            test.client_request('/action', {'name': human, 'action': 'release'})
            test.sprint(2)
            test.check('ship part submitted: ' + part, test.score('$game', 'ship_parts') == number)
        test.sprint(2050)
        test.check('ship repair opens boarding', test.score('$game', 'cur_phase') == 4 and test.score('$game', 'ship_countdown') > 0 and test.count('@e[type=minecraft:interaction,tag=entity.ship_door]') == 1)
        pos = test.cmd('data get entity @e[type=minecraft:interaction,tag=entity.ship_door,limit=1] Pos')
        values = re.findall(r'(-?\d+(?:\.\d+)?)d', pos)
        if len(values) != 3:
            raise AssertionError('Cannot read ship door position: ' + pos)
        x, y, z = map(float, values)
        test.cmd(f'tp {human} {x} {y} {z}')
        test.sprint(2)
        time.sleep(.5)
        entities = test.client_request('/entities?name=' + human)
        nearby = sorted(entities, key=lambda e: sum((e['position'][k] - v) ** 2 for k, v in zip(('x', 'y', 'z'), (x, y, z))))
        if not nearby:
            raise AssertionError('Client did not receive ship interaction entity')
        test.client_request('/action', {'name': human, 'action': 'interact', 'entity': nearby[0]['id']})
        test.sprint(2)
        test.check('client boards ship', test.count(f'@a[name={human},tag=state.boarding.ship]') == 1)
        prior = test.score('$game', 'ie.settle_count')
        test.sprint(1000)
        test.check('ship departure settles escape once', test.score('$game', 'in_game') == 0 and test.score('$game', 'escape_route') == 2 and test.score('$game', 'escaped_count') >= 1 and test.score('$game', 'ie.settle_count') == prior + 1)
    finally:
        test.close('ship-results.json')


if __name__ == '__main__':
    main()
